#!/usr/bin/env python3
"""Compiles native/gfx/render/builtin/*.{vert,frag} with glslc into builtin_shaders.inc (SPIR-V as C arrays), which is committed so that building the renderer needs no shader compiler.
   The shaders stand in for the D3D library's own microcode (see the comments of each source). Usage: python3 gen_builtin_shaders.py (needs glslc)"""
import pathlib, subprocess, struct, tempfile
here = pathlib.Path(__file__).resolve().parent
out = ["// Generated by gen_builtin_shaders.py from builtin/*: do not edit.\n"]
for src in sorted((here / "builtin").glob("*.*")):
    if src.suffix not in (".vert", ".frag"): continue
    with tempfile.NamedTemporaryFile(suffix=".spv") as f:
        subprocess.run(["glslc", "-O", "--target-env=vulkan1.3", str(src), "-o", f.name], check=True)
        data = pathlib.Path(f.name).read_bytes()
    words = struct.unpack("<%dI" % (len(data) // 4), data)
    name = "k" + "".join(p.capitalize() for p in src.stem.split("_")) + src.suffix[1:].capitalize()
    out.append("static const uint32_t %s[] = {%s};\n" % (name, ",".join("0x%08x" % w for w in words)))
(here / "builtin_shaders.inc").write_text("".join(out))
print("wrote builtin_shaders.inc")
