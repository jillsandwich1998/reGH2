#!/usr/bin/env python3
"""Generates native/gfx/guest_d3d/d3d_probe.gen.cpp: one observing hook per function of the D3D library block of the game.

  gen_d3d_probes.py GENERATED_DIR [--lo 823C0000 --hi 823E0000] [--extra ADDR ...] [--skip ADDR ...] [--check]

GENERATED_DIR is the codegen output (work/<project>/generated/default): the function addresses come from its gh2_register.cpp.
Functions that already have a hand-written hook get no generated wrapper (two hooks cannot own one symbol): the ones in native/rt/hooks/hooked_functions.txt
and native/gfx/guest_d3d/semantic_hooks.txt, plus any --skip. The semantic hooks stay in the function table and record themselves (ProbeScope in d3d_hooks.cpp), so
the window recordings still show every call.
Each generated hook overrides the weak guest function `sub_X` and calls the original `__imp__sub_X` (the generated code defines both).
"""
import argparse
import pathlib
import re
import sys

OUT = pathlib.Path(__file__).resolve().parents[1] / "gfx/guest_d3d/d3d_probe.gen.cpp"
RX = re.compile(r"SetFunction\(0x([0-9A-F]{8}), sub_([0-9A-F]{8})\)")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("generated")
    ap.add_argument("--lo", default="823B0000")
    ap.add_argument("--hi", default="823E0000")
    ap.add_argument("--extra", nargs="*", default=[])
    ap.add_argument("--skip", nargs="*", default=[])
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    lo, hi = int(a.lo, 16), int(a.hi, 16)
    native = pathlib.Path(__file__).resolve().parents[1]
    semantic = set()
    for listing in (native / "rt/hooks/hooked_functions.txt", native / "gfx/guest_d3d/semantic_hooks.txt"):
        if listing.exists():
            for line in listing.read_text().splitlines():
                line = line.split("#")[0].strip()
                if line:
                    a.skip.append(line.replace("sub_", ""))
                    if listing.name == "semantic_hooks.txt":
                        semantic.add(int(line.replace("sub_", ""), 16))
    src = (pathlib.Path(a.generated) / "gh2_register.cpp").read_text()
    funcs = {int(m.group(1), 16) for m in RX.finditer(src)}
    skip = {int(x, 16) for x in a.skip}
    extra = {int(e, 16) for e in a.extra}
    chosen = sorted(x for x in funcs if (lo <= x < hi or x in extra) and (x not in skip or x in semantic))
    lines = [
        "// GENERATED by native/tools/gen_d3d_probes.py from the codegen output. Do not edit.",
        "// One observing hook per function of the D3D library block (see gh2gfx/d3d_probe.h). Off unless GH2_D3D_PROBE=<prefix>.",
        '#include "gh2_pch.h"  // PPCContext, REX_EXTERN',
        "",
        "#include <gh2gfx/d3d_probe.h>",
        "",
        "#define GH2_D3D_PROBE_FN(IDX, ADDR)                                                                                      \\",
        "  REX_EXTERN(__imp__sub_##ADDR);                                                                                         \\",
        "  REX_EXTERN(sub_##ADDR) {                                                                                               \\",
        "    if (!::gh2gfx::d3d::ProbeEnabled()) {                                                                                \\",
        "      __imp__sub_##ADDR(ctx, base);                                                                                      \\",
        "      return;                                                                                                            \\",
        "    }                                                                                                                    \\",
        "    const uint32_t a[6] = {ctx.r3.u32, ctx.r4.u32, ctx.r5.u32, ctx.r6.u32, ctx.r7.u32, ctx.r8.u32};                     \\",
        "    ::gh2gfx::d3d::ProbeEnter(IDX, a, base);                                                                             \\",
        "    __imp__sub_##ADDR(ctx, base);                                                                                        \\",
        "    ::gh2gfx::d3d::ProbeLeave(IDX, ctx.r3.u32, a, base);                                                                 \\",
        "  }",
        "",
    ]
    for i, f in enumerate(chosen):
        if f not in skip:
            lines.append("GH2_D3D_PROBE_FN(%d, %08X)" % (i, f))
    lines += ["", "namespace gh2gfx::d3d {", "const uint32_t kProbeFunctions[] = {"]
    for i in range(0, len(chosen), 6):
        lines.append("    " + ", ".join("0x%08X" % f for f in chosen[i:i + 6]) + ",")
    lines += ["};", "const uint32_t kProbeFunctionCount = %d;" % len(chosen), "}  // namespace gh2gfx::d3d", ""]
    text = "\n".join(lines)
    if a.check:
        ok = OUT.exists() and OUT.read_text() == text
        print("d3d_probe.gen.cpp is up to date" if ok else "d3d_probe.gen.cpp is stale: run gen_d3d_probes.py")
        sys.exit(0 if ok else 1)
    OUT.write_text(text)
    print("wrote %s: %d functions" % (OUT, len(chosen)))


if __name__ == "__main__":
    main()
