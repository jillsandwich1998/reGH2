#!/usr/bin/env python3
"""Generates the stubs of the game module boundary (native/rt/module, gh2module/game_module.h).

  overrides  --nm LLVM_NM --out overrides.txt OBJ...
             the game functions the host overrides: every `sub_<8 hex>` / `xstart` the given objects (the hooks') define
  game       --imports imports.txt --overrides overrides.txt --out gh2game_stubs.gen.cpp
             module side: `__imp__<Name>` stubs that jump through the host's import table, strong `sub_X` stubs that jump to the host's
             hooks (they win over the generated weak alias), and the table of the original code (`__imp__sub_X`)
  host       --imports imports.txt --overrides overrides.txt --out gh2host_stubs.gen.cpp
             host side: the table of the (wrapped) kernel imports, the table of the hooks, and `__imp__sub_X` stubs that jump to the
             module's original code

Both sides embed the FNV-1a hash of the two lists; the handshake refuses a module generated from other lists.
"""
import argparse
import pathlib
import re
import subprocess
import sys

OVERRIDE_RE = re.compile(r"^(sub_[0-9A-F]{8}|xstart)$")


def fnv1a(names):
    h = 0xCBF29CE484222325
    for b in "".join(n + "\n" for n in names).encode():
        h = ((h ^ b) * 0x100000001B3) & 0xFFFFFFFFFFFFFFFF
    return h


def read_list(path):
    names = pathlib.Path(path).read_text().split()
    if len(set(names)) != len(names):
        sys.exit("%s: duplicate names" % path)
    return names


def write_if_changed(path, text):
    p = pathlib.Path(path)
    if p.exists() and p.read_text() == text:
        return
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text, newline="\n")


def scan_overrides(nm, objects):
    found = set()
    for obj in objects:
        out = subprocess.run([nm, "--defined-only", "--extern-only", "-j", obj], capture_output=True, text=True)
        if out.returncode != 0:
            sys.exit("%s failed on %s:\n%s" % (nm, obj, out.stderr))
        found.update(n for n in out.stdout.split() if OVERRIDE_RE.match(n))
    return sorted(found)


HEADER = ("// GENERATED by native/tools/gen_module_stubs.py from %s and %s. Do not edit.\n"
          "// imports: %d (hash %016X), overrides: %d (hash %016X)\n"
          "#include <gh2module/game_module.h>\n")


def game_side(imports, overrides, src):
    ih, oh = fnv1a(imports), fnv1a(overrides)
    out = [HEADER % (src[0], src[1], len(imports), ih, len(overrides), oh), 'extern "C" {',
           "Gh2PPCFunc* gh2m_imports[%d];" % len(imports),
           "Gh2PPCFunc* gh2m_overrides[%d];" % len(overrides),
           "extern const uint32_t gh2m_import_count = %d;" % len(imports),
           "extern const uint32_t gh2m_override_count = %d;" % len(overrides),
           "extern const uint64_t gh2m_imports_hash = 0x%016Xull;" % ih,
           "extern const uint64_t gh2m_overrides_hash = 0x%016Xull;" % oh,
           "",
           "// kernel imports: the generated code calls these; the host's (wrapped) implementation runs"]
    for i, n in enumerate(imports):
        out.append("void __imp__%s(PPCContext& c, uint8_t* b) { [[clang::musttail]] return gh2m_imports[%d](c, b); }" % (n, i))
    out += ["", "// overridden game functions: these strong definitions replace the generated weak alias, so every call reaches the host's hook"]
    for i, n in enumerate(overrides):
        out.append("void %s(PPCContext& c, uint8_t* b) { [[clang::musttail]] return gh2m_overrides[%d](c, b); }" % (n, i))
    out += ["", "// the game's own code of the overridden functions, for the hooks that call it"]
    out += ["Gh2PPCFunc __imp__%s;" % n for n in overrides]
    out.append("extern Gh2PPCFunc* const gh2m_originals[%d] = {" % len(overrides))
    out += ["    __imp__%s," % n for n in overrides]
    out += ["};", '}  // extern "C"', ""]
    return "\n".join(out)


def host_side(imports, overrides, src):
    ih, oh = fnv1a(imports), fnv1a(overrides)
    out = [HEADER % (src[0], src[1], len(imports), ih, len(overrides), oh), 'extern "C" {',
           "extern const uint32_t gh2h_import_count = %d;" % len(imports),
           "extern const uint32_t gh2h_override_count = %d;" % len(overrides),
           "extern const uint64_t gh2h_imports_hash = 0x%016Xull;" % ih,
           "extern const uint64_t gh2h_overrides_hash = 0x%016Xull;" % oh,
           "",
           "// kernel imports (the link's /wrap: turns these references into the tracing wrappers and the hooks, as for the game code)"]
    out += ["Gh2PPCFunc __imp__%s;" % n for n in imports]
    out.append("extern Gh2PPCFunc* const gh2h_imports[%d] = {" % len(imports))
    out += ["    __imp__%s," % n for n in imports]
    out += ["};", "", "// the hooks"]
    out += ["Gh2PPCFunc %s;" % n for n in overrides]
    out.append("extern Gh2PPCFunc* const gh2h_overrides[%d] = {" % len(overrides))
    out += ["    %s," % n for n in overrides]
    out += ["};", "", "// the game's original code, filled from the module at load (gh2module::OpenGameModule)",
            "Gh2PPCFunc* gh2h_originals[%d];" % len(overrides)]
    for i, n in enumerate(overrides):
        out.append("void __imp__%s(PPCContext& c, uint8_t* b) { [[clang::musttail]] return gh2h_originals[%d](c, b); }" % (n, i))
    out += ['}  // extern "C"', ""]
    return "\n".join(out)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    o = sub.add_parser("overrides")
    o.add_argument("--nm", required=True)
    o.add_argument("--out", required=True)
    o.add_argument("objects", nargs="+")
    for name in ("game", "host"):
        s = sub.add_parser(name)
        s.add_argument("--imports", required=True)
        s.add_argument("--overrides", required=True)
        s.add_argument("--out", required=True)
    a = ap.parse_args()
    if a.cmd == "overrides":
        names = scan_overrides(a.nm, a.objects)
        if not names:
            sys.exit("no overridden game function found in %d objects" % len(a.objects))
        write_if_changed(a.out, "".join(n + "\n" for n in names))
        return
    imports, overrides = read_list(a.imports), read_list(a.overrides)
    src = (pathlib.Path(a.imports).name, pathlib.Path(a.overrides).name)
    write_if_changed(a.out, (game_side if a.cmd == "game" else host_side)(imports, overrides, src))


if __name__ == "__main__":
    main()
