#!/usr/bin/env python3
"""Generates the boundary-tracer import wrappers from the contract.

  inputs : native/rt/abi/contract/imports.txt   (the 179 kernel imports the generated code calls)
           native/rt/hooks/hooked_imports.txt   (imports that have a hand-written hook; they call GH2_TRACE_HOOK themselves)
  outputs: native/rt/trace/import_trace.gen.cpp (name table + __wrap___imp__<Name> for every non-hooked import)
           native/rt/trace/trace_wraps.cmake    (GH2_TRACE_WRAP_FLAGS = -Wl,--wrap=__imp__<Name> for every non-hooked import)
Run from anywhere: gen_import_tracer.py   (add --check to fail when the committed outputs are stale)
"""
import pathlib
import sys

NATIVE = pathlib.Path(__file__).resolve().parents[1]
IMPORTS = NATIVE / "rt/abi/contract/imports.txt"
HOOKED = NATIVE / "rt/hooks/hooked_imports.txt"
OUT_CPP = NATIVE / "rt/trace/import_trace.gen.cpp"
OUT_CMAKE = NATIVE / "rt/trace/trace_wraps.cmake"


def build():
    names = IMPORTS.read_text().split()
    hooked = set(HOOKED.read_text().split())
    unknown = hooked - set(names)
    if unknown:
        sys.exit("hooked_imports.txt names that are not imports: %s" % sorted(unknown))
    cpp = ["// GENERATED by native/tools/gen_import_tracer.py from contract/imports.txt and hooks/hooked_imports.txt. Do not edit.",
           "// Name table of the boundary trace + one tracing wrapper per import that has no hand-written hook.",
           "#include <gh2rt/boundary_trace.h>",
           "",
           "#include <rex/ppc/context.h>",
           "",
           "#define GH2_TRACE_WRAP(NAME, ID)                                                    \\",
           "  extern \"C\" void __real___imp__##NAME(PPCContext&, uint8_t*);                      \\",
           "  extern \"C\" void __wrap___imp__##NAME(PPCContext& __restrict ctx, uint8_t* base) { \\",
           "    ::gh2rt::trace::Scope<PPCContext> scope(ID, ctx);                               \\",
           "    __real___imp__##NAME(ctx, base);                                                \\",
           "  }",
           "",
           "namespace gh2rt::trace {",
           "extern const char* const kImportNames[] = {"]
    cpp += ['    "%s",' % n for n in names]
    cpp += ["};", "extern const size_t kImportNameCount = %d;" % len(names), "}  // namespace gh2rt::trace", ""]
    for i, n in enumerate(names):
        if n not in hooked:
            cpp.append("GH2_TRACE_WRAP(%s, %d)" % (n, i))
    flags = " ".join("-Wl,--wrap=__imp__%s" % n for n in names if n not in hooked)
    cmake = ["# GENERATED by native/tools/gen_import_tracer.py. Do not edit.",
             "# GH2_TRACE_WRAP_FLAGS: imports wrapped by the generated tracing wrappers; GH2_HOOK_WRAP_FLAGS: imports with a hand-written hook.",
             "set(GH2_TRACE_WRAP_FLAGS"] + ["    -Wl,--wrap=__imp__%s" % n for n in names if n not in hooked] + [")",
             "set(GH2_HOOK_WRAP_FLAGS"] + ["    -Wl,--wrap=__imp__%s" % n for n in names if n in hooked] + [")", ""]
    return "\n".join(cpp) + "\n", "\n".join(cmake)


def main():
    cpp, cmake = build()
    if "--check" in sys.argv:
        ok = OUT_CPP.exists() and OUT_CPP.read_text() == cpp and OUT_CMAKE.exists() and OUT_CMAKE.read_text() == cmake
        print("tracer wrappers are %s" % ("up to date" if ok else "STALE: run native/tools/gen_import_tracer.py"))
        sys.exit(0 if ok else 1)
    OUT_CPP.write_text(cpp)
    OUT_CMAKE.write_text(cmake)
    n = len(IMPORTS.read_text().split())
    h = len(set(HOOKED.read_text().split()))
    print("wrote %s and %s: %d imports, %d wrappers generated, %d hooked" % (OUT_CPP.name, OUT_CMAKE.name, n, n - h, h))


if __name__ == "__main__":
    main()
